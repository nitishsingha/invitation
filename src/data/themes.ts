export function getThemesForCategory(categorySlug: string, isCustomCategory = false): InvitationTheme[] {
  const exact = BUILT_IN_THEMES.filter((t) => t.categorySlug === categorySlug && t.isActive);
  if (exact.length > 0) return exact;
  if (isCustomCategory) {
    return BUILT_IN_THEMES.filter((t) => t.categorySlug === 'custom' && t.isActive);
  }
  return BUILT_IN_THEMES.filter((t) => t.categorySlug === 'custom' && t.isActive);
}

export function getThemeById(themeId: string): InvitationTheme {
  return BUILT_IN_THEMES.find((t) => t.id === themeId) ?? BUILT_IN_THEMES[0];
}
